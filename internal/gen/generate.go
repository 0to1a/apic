package gen

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/format"
	"strings"
	"text/template"

	"github.com/0to1a/apic/internal/ir"
)

//go:embed runtime/bind.go
var runtimeBind string

//go:embed runtime/codes.go
var runtimeCodes string

//go:embed runtime/envelope.go
var runtimeEnvelope string

//go:embed runtime/options.go
var runtimeOptions string

//go:embed runtime/status.go
var runtimeStatus string

// runtimeHeader marks a runtime file as generated output, same as every
// templated file below.
const runtimeHeader = "// Code generated by apic. DO NOT EDIT.\n\n"

// rewriteRuntime turns an internal/gen/runtime source file (package runtime)
// into a gen/ output file (package gen), prefixed with the generated-code
// header.
func rewriteRuntime(src string) []byte {
	return []byte(runtimeHeader + strings.Replace(src, "package runtime", "package gen", 1))
}

// Generate renders a resolved contract into the gen/ package files. Callers
// are expected to have already run ir.Validate + ir.Resolve successfully.
func Generate(c *ir.ContractIR) (map[string][]byte, error) {
	files := map[string]*template.Template{
		"types.go":      typesTmpl,
		"service.go":    serviceTmpl,
		"middleware.go": middlewareTmpl,
		"routes.go":     routesTmpl,
	}
	out := make(map[string][]byte, len(files))
	for name, tmpl := range files {
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, c); err != nil {
			return nil, fmt.Errorf("render %s: %w", name, err)
		}
		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("format %s: %w\n--- unformatted source ---\n%s", name, err, buf.String())
		}
		out[name] = formatted
	}

	for name, src := range map[string]string{
		"bind.go":     runtimeBind,
		"codes.go":    runtimeCodes,
		"envelope.go": runtimeEnvelope,
		"options.go":  runtimeOptions,
		"status.go":   runtimeStatus,
	} {
		out[name] = rewriteRuntime(src)
	}

	return out, nil
}
