var funcMap = template.FuncMap{
	"goType":  ir.GoTypeString,
	"tag":     ir.StructTag,
	"isCtx":   func(f ir.FieldIR) bool { return f.Source == ir.SourceCtx },
	"untitle": untitle,
}

// untitle lowercases the first rune of s, used to derive a local variable
// name from a field's Go name (e.g. "Auth" -> "auth").
func untitle(s string) string {
	if s == "" {
		return s
	}
	r, size := utf8.DecodeRuneInString(s)
	return string(unicode.ToLower(r)) + s[size:]
}

