var funcMap = template.FuncMap{
	"goType":  ir.GoTypeString,
	"tag":     ir.StructTag,
	"isCtx":   func(f ir.FieldIR) bool { return f.Source == ir.SourceCtx },
	"untitle": ir.Untitle,
	"anyProvides": func(mws []ir.MiddlewareIR) bool {
		for _, m := range mws {
			if m.Provides != "" {
				return true
			}
		}
		return false
	},
}

